# Inicialize o repositório local
git init

# Adicione os arquivos
git add .

# Commit inicial
git commit -m "Primeiro commit - Projeto completo de conversão de áudio para vídeo"

# Conecte ao repositório remoto (substitua <seu-usuario> pelo seu nome no GitHub)
git remote add origin https://github.com/<seu-usuario>/audio-to-video.git

# Envie os arquivos
git push -u origin master